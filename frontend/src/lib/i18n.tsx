const dictionaries: Record<Language, Dictionary> = { en, zh, hi, es, fr, ar, bn, pt, ru, ur };

const htmlLang: Record<Language, string> = {
  en: "en",
  zh: "zh-CN",
  hi: "hi-IN",
  es: "es-ES",
  fr: "fr-FR",
  ar: "ar",
  bn: "bn-BD",
  pt: "pt-BR",
  ru: "ru-RU",
  ur: "ur-PK",
};

function detectLanguage(): Language {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored && stored in dictionaries) return stored as Language;
  } catch {
    // Storage may be unavailable.
  }
  const browser = (navigator.language || "").toLowerCase();
  const match = languages.find((item) => item.id !== "en" && browser.startsWith(item.id));
  if (match) return match.id;
  if (browser.startsWith("zh")) return "zh";
  return "en";
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: Translate;
}

const I18nContext = createContext<I18nContextValue>({
  language: "en",
  setLanguage: () => undefined,
  t: (key, vars) => interpolate(en[key], vars),
});

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(detectLanguage);

  useEffect(() => {
    const meta = languages.find((item) => item.id === language) ?? languages[0];
    document.documentElement.lang = htmlLang[language];
    document.documentElement.dir = meta.dir;
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Storage may be unavailable.
    }
  }, [language]);

  const setLanguage = useCallback((next: Language) => setLanguageState(next), []);
  const t = useCallback<Translate>(
    (key, vars) => interpolate(dictionaries[language][key] ?? en[key], vars),
    [language],
  );
  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function LanguageToggle({ compact = false }: { compact?: boolean }) {
  const { language, setLanguage, t } = useI18n();
  return (
    <label className="inline-flex items-center gap-1 rounded-md border bg-card/60 px-1.5 py-0.5">
      <span className="sr-only">{t("common.language")}</span>
      <select
        aria-label={t("common.language")}
        value={language}
        onChange={(event) => setLanguage(event.target.value as Language)}
        className={`cursor-pointer bg-transparent text-[10px] font-medium text-muted-foreground outline-none ${
          compact ? "max-w-[4.5rem]" : "max-w-[7rem]"
        }`}
      >
        {languages.map((item) => (
          <option key={item.id} value={item.id}>
            {item.label}
          </option>
        ))}
      </select>
    </label>
  );
}
